const fs = require('fs');
const path = require('path');

const version = Date.now().toString();

const versionData = {
    version: version,
    timestamp: new Date().toISOString()
};

// Paths
const publicDir = path.join(__dirname, '../busgo/public');
const srcDir = path.join(__dirname, '../busgo/src');

// Ensure directories exist
if (!fs.existsSync(publicDir)) {
    console.error(`Public directory not found: ${publicDir}`);
    process.exit(1);
}
if (!fs.existsSync(srcDir)) {
    console.error(`Src directory not found: ${srcDir}`);
    process.exit(1);
}

// 1. Write public/version.json (Server Version)
const publicPath = path.join(publicDir, 'version.json');
fs.writeFileSync(publicPath, JSON.stringify(versionData, null, 2));
console.log(`Generated ${publicPath}`);

// 2. Write src/currentVersion.js (Client Version)
const srcPath = path.join(srcDir, 'currentVersion.js');
const srcContent = `// This file is auto-generated by scripts/bump_version.js
export const CURRENT_VERSION = "${version}";
export const BUILD_DATE = "${new Date().toISOString()}";
`;
fs.writeFileSync(srcPath, srcContent);
console.log(`Generated ${srcPath}`);

console.log(`\nVersion bumped to: ${version}`);
console.log('Ensure you deploy both the new build and the public/version.json file.');
